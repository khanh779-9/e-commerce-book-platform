import * as dotenv from 'dotenv';
import * as fs from 'fs';
import * as path from 'path';

/**
 * Generate environment.base.ts from .env file.
 * Run before Angular build to inject environment variables.
 */

// Determine mode: 'production' | 'development'
const mode = process.env['NG_BUILD_MODE'] || 'development';
const envFile = mode === 'production' ? '.env.production' : '.env';
const envPath = path.resolve(process.cwd(), envFile);

// Load .env file if exists
const envVars = { PORT: '5000', FRONTEND_URL_DEV: 'http://localhost:4200', FRONTEND_URL_SSR: 'http://localhost:5000', BACKEND_URL: 'http://localhost:5132' };

if (fs.existsSync(envPath)) {
  const result = dotenv.config({ path: envPath });
  if (result.error) {
    console.warn(`⚠️  Failed to load ${envFile}:`, result.error.message);
  } else {
    Object.assign(envVars, result.parsed);
    console.log(`✅ Loaded ${envFile} for ${mode} build`);
  }
} else {
  console.warn(`⚠️  ${envFile} not found, using defaults`);
}

// Ensure BACKEND_URL has no trailing slash
const backendUrl = (envVars.BACKEND_URL || 'http://localhost:5132').replace(/\/$/, '');

// Generate environment.base.ts content
const content = `/**
 * Base environment configuration shared between dev and prod.
 * AUTO-GENERATED by scripts/gen-env.mjs - DO NOT EDIT MANUALLY.
 * Source: ${envFile} (${mode})
 */

export const baseEnvironment = {
  // URLs - injected from ${envFile}
  frontendUrl: '${envVars.FRONTEND_URL_SSR || 'http://localhost:5000'}',
  backendUrl: '${backendUrl}',
  frontendUrlDev: '${envVars.FRONTEND_URL_DEV || 'http://localhost:4200'}',

  appName: 'BookZone',
  version: '1.0.0',
};
`;

// Write to environment.base.ts
const outputPath = path.resolve(process.cwd(), 'src/environments/environment.base.ts');
fs.writeFileSync(outputPath, content);
console.log(`✅ Generated ${outputPath}`);